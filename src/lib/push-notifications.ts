/**
 * @file push-notifications.ts
 * @description Web Push Notification & Browser FCM Token Manager.
 * Optimized with service worker pre-warming, promise caching, and request deduplication.
 */

import { initializeApp, getApps, getApp } from "firebase/app"
import {
  getMessaging,
  getToken,
  deleteToken,
  onMessage,
  isSupported,
  Messaging,
} from "firebase/messaging"
import firebaseConfig, { FIREBASE_VAPID_KEY } from "@/config/firebase.config"

const FCM_TOKEN_STORAGE_KEY = "meeo_fcm_token"

export type PushPermissionStatus =
  | "granted"
  | "denied"
  | "default"
  | "unsupported"

// Firebase v12 added an experimental Installation ID (FID) API (register/onRegistered)
// and marked getToken/deleteToken with @deprecated JSDoc tags. However, backend push
// providers (including Firebase Admin SDK admin.messaging().send) require the FCM registration
// token generated by getToken. We type-cast the functions to prevent editor ts(6387) warnings.
type GetTokenFunction = (
  messaging: Messaging,
  options?: { vapidKey?: string; serviceWorkerRegistration?: ServiceWorkerRegistration }
) => Promise<string>

type DeleteTokenFunction = (messaging: Messaging) => Promise<boolean>

const getFcmToken: GetTokenFunction = getToken as unknown as GetTokenFunction
const deleteFcmToken: DeleteTokenFunction = deleteToken as unknown as DeleteTokenFunction

// Singletons for caching promises and instances
let messagingPromise: Promise<Messaging | null> | null = null
let swRegistrationPromise: Promise<ServiceWorkerRegistration | undefined> | null = null
let inFlightTokenPromise: Promise<string | null> | null = null

/**
 * Check if the current browser environment supports Push Notifications & Service Workers.
 */
export function isPushNotificationSupported(): boolean {
  return (
    typeof window !== "undefined" &&
    "Notification" in window &&
    "serviceWorker" in navigator &&
    "PushManager" in window
  )
}

/**
 * Get current browser notification permission status.
 */
export function getPushPermissionStatus(): PushPermissionStatus {
  if (!isPushNotificationSupported()) {
    return "unsupported"
  }
  return Notification.permission
}

/**
 * Retrieve cached device token from localStorage.
 */
export function getLocalDeviceToken(): string | null {
  if (typeof window === "undefined") return null
  try {
    return localStorage.getItem(FCM_TOKEN_STORAGE_KEY)
  } catch {
    return null
  }
}

/**
 * Save device token to localStorage.
 */
export function setLocalDeviceToken(token: string): void {
  if (typeof window === "undefined") return
  try {
    localStorage.setItem(FCM_TOKEN_STORAGE_KEY, token)
  } catch {
    // Ignore storage quota or access errors
  }
}

/**
 * Remove device token from localStorage.
 */
export function clearLocalDeviceToken(): void {
  if (typeof window === "undefined") return
  try {
    localStorage.removeItem(FCM_TOKEN_STORAGE_KEY)
  } catch {
    // Ignore storage errors
  }
}

/**
 * Initialize Firebase app instance safely.
 */
function getFirebaseAppInstance() {
  if (getApps().length > 0) {
    return getApp()
  }
  return initializeApp(firebaseConfig)
}

/**
 * Initialize Firebase Messaging instance with cached promise to eliminate repeated capability checks.
 */
export function getFirebaseMessaging(): Promise<Messaging | null> {
  if (!isPushNotificationSupported()) return Promise.resolve(null)
  if (messagingPromise) return messagingPromise

  messagingPromise = (async () => {
    try {
      const supported = await isSupported()
      if (!supported) return null
      const app = getFirebaseAppInstance()
      return getMessaging(app)
    } catch (err) {
      console.warn("Failed to initialize Firebase Messaging:", err)
      return null
    }
  })()

  return messagingPromise
}

/**
 * Get or register the Firebase Messaging Service Worker. Reuses existing active registration.
 */
export function getOrRegisterPushServiceWorker(): Promise<ServiceWorkerRegistration | undefined> {
  if (typeof window === "undefined" || !("serviceWorker" in navigator)) {
    return Promise.resolve(undefined)
  }

  if (swRegistrationPromise) {
    return swRegistrationPromise
  }

  swRegistrationPromise = (async () => {
    try {
      // Check if already registered
      const existing = await navigator.serviceWorker.getRegistration("/")
      if (existing && existing.active?.scriptURL?.includes("firebase-messaging-sw")) {
        return existing
      }

      const swUrl = new URL("/firebase-messaging-sw.js", window.location.origin)
      if (firebaseConfig.apiKey) swUrl.searchParams.set("apiKey", firebaseConfig.apiKey)
      if (firebaseConfig.projectId) swUrl.searchParams.set("projectId", firebaseConfig.projectId)
      if (firebaseConfig.messagingSenderId)
        swUrl.searchParams.set("messagingSenderId", firebaseConfig.messagingSenderId)
      if (firebaseConfig.appId) swUrl.searchParams.set("appId", firebaseConfig.appId)

      const registration = await navigator.serviceWorker.register(
        `${swUrl.pathname}${swUrl.search}`,
        { scope: "/" }
      )
      await navigator.serviceWorker.ready
      return registration
    } catch (swErr) {
      console.warn("Service worker registration error:", swErr)
      return undefined
    }
  })()

  return swRegistrationPromise
}

/**
 * Pre-warm the Push Service Worker and Firebase Messaging in the background.
 */
export function prewarmPushServiceWorker(): void {
  if (!isPushNotificationSupported()) return
  if (typeof window !== "undefined") {
    const warm = () => {
      getOrRegisterPushServiceWorker().catch(() => {})
      getFirebaseMessaging().catch(() => {})
    }
    if ("requestIdleCallback" in window) {
      (window as Window & { requestIdleCallback: (cb: () => void) => void }).requestIdleCallback(warm)
    } else {
      setTimeout(warm, 1000)
    }
  }
}

/**
 * Request Notification Permission and retrieve FCM Device Token.
 * Deduplicates in-flight calls to prevent concurrent race conditions.
 */
export async function requestWebPushToken(forceRefresh = false): Promise<string | null> {
  if (!isPushNotificationSupported()) {
    return null
  }

  // Deduplicate concurrent token requests
  if (inFlightTokenPromise && !forceRefresh) {
    return inFlightTokenPromise
  }

  inFlightTokenPromise = (async () => {
    try {
      // 1. Request browser permission directly
      const permission = await Notification.requestPermission()
      if (permission !== "granted") {
        clearLocalDeviceToken()
        return null
      }

      // Fast-path: If permission is already granted and we already have a valid local token, reuse it
      const existingToken = getLocalDeviceToken()
      if (existingToken && !forceRefresh) {
        return existingToken
      }

      // 2. Obtain Firebase Messaging instance and Service Worker in parallel
      const [messaging, swRegistration] = await Promise.all([
        getFirebaseMessaging(),
        getOrRegisterPushServiceWorker(),
      ])

      if (!messaging) return null

      if (forceRefresh) {
        clearLocalDeviceToken()
        try {
          await deleteFcmToken(messaging)
        } catch {}
      }

      // 3. Generate fresh FCM token from Firebase
      const token = await getFcmToken(messaging, {
        vapidKey: FIREBASE_VAPID_KEY || undefined,
        serviceWorkerRegistration: swRegistration,
      })

      if (token) {
        setLocalDeviceToken(token)
        return token
      }
      return null
    } catch (tokenErr) {
      console.error("Failed to generate FCM web token:", tokenErr)
      return null
    } finally {
      inFlightTokenPromise = null
    }
  })()

  return inFlightTokenPromise
}

/**
 * Unregister FCM push token in Firebase and remove from local storage.
 */
export async function unregisterWebPushToken(): Promise<string | null> {
  const currentToken = getLocalDeviceToken()
  try {
    const messaging = await getFirebaseMessaging()
    if (messaging) {
      await deleteFcmToken(messaging)
    }
  } catch (err) {
    console.warn("Error deleting Firebase FCM token:", err)
  } finally {
    clearLocalDeviceToken()
    swRegistrationPromise = null
  }
  return currentToken
}

export interface PushMessagePayload {
  notification?: {
    title?: string
    body?: string
    image?: string
    icon?: string
  }
  data?: Record<string, any>
  fcmOptions?: {
    link?: string
    analyticsLabel?: string
  }
  from?: string
  collapseKey?: string
  messageId?: string
}

/**
 * Subscribe to foreground push messages while app is in active tab.
 */
export function onForegroundPushMessage(callback: (payload: PushMessagePayload) => void): () => void {
  if (!isPushNotificationSupported()) return () => {}

  let unsubscribe: (() => void) | null = null

  getFirebaseMessaging().then((messaging) => {
    if (messaging) {
      unsubscribe = onMessage(messaging, (payload) => {
        callback(payload as PushMessagePayload)
      })
    }
  })

  return () => {
    if (unsubscribe) {
      unsubscribe()
    }
  }
}

/**
 * Fully reset push notification state: remove local storage token, delete token in Firebase, and unregister sw.
 */
export async function resetPushNotificationCache(): Promise<void> {
  clearLocalDeviceToken()
  swRegistrationPromise = null
  messagingPromise = null
  inFlightTokenPromise = null

  try {
    const messaging = await getFirebaseMessaging()
    if (messaging) {
      await deleteFcmToken(messaging)
    }
  } catch {}

  if (typeof navigator !== "undefined" && "serviceWorker" in navigator) {
    try {
      const registrations = await navigator.serviceWorker.getRegistrations()
      for (const reg of registrations) {
        if (reg.active?.scriptURL?.includes("firebase-messaging-sw")) {
          await reg.unregister()
        }
      }
    } catch {}
  }
}
